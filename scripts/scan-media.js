/**
 * DJ John - Media Folder Auto-Scanner
 * Scans `assets/media/photos/` and `assets/media/videos/` and updates `assets/media/gallery-manifest.js`.
 * Run using: node scripts/scan-media.js
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const projectRoot = path.resolve(__dirname, '..');
const photosDir = path.join(projectRoot, 'assets', 'media', 'photos');
const videosDir = path.join(projectRoot, 'assets', 'media', 'videos');
const manifestPath = path.join(projectRoot, 'assets', 'media', 'gallery-manifest.js');

const photoExts = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif']);
const videoExts = new Set(['.mp4', '.webm', '.mov', '.m4v', '.ogg']);

function humanize(filename) {
  const nameWithoutExt = path.parse(filename).name;
  return nameWithoutExt
    .replace(/[-_]+/g, ' ')
    .replace(/\b\w/g, (char) => char.toUpperCase());
}

function detectCategory(filename) {
  const lower = filename.toLowerCase();
  if (lower.includes('wed') || lower.includes('sangeet') || lower.includes('reception') || lower.includes('entry')) return 'wedding';
  if (lower.includes('birth') || lower.includes('bday') || lower.includes('cake')) return 'birthday';
  if (lower.includes('club') || lower.includes('dance') || lower.includes('edm') || lower.includes('bass')) return 'parties';
  return 'celebrations';
}

function scanDir(dirPath, type, validExts, urlPrefix) {
  if (!fs.existsSync(dirPath)) return [];
  const files = fs.readdirSync(dirPath);
  const items = [];

  for (const file of files) {
    const ext = path.extname(file).toLowerCase();
    if (validExts.has(ext)) {
      items.push({
        id: `local-${type}-${path.parse(file).name}`,
        type,
        title: humanize(file),
        category: detectCategory(file),
        src: `${urlPrefix}/${file}`,
        caption: `Live performance media recorded at DJ John event.`
      });
    }
  }

  return items;
}

const localPhotos = scanDir(photosDir, 'photo', photoExts, './assets/media/photos');
const localVideos = scanDir(videosDir, 'video', videoExts, './assets/media/videos');

const localItems = [...localVideos, ...localPhotos];

// Read existing sample fallback items
let sampleItems = [];
try {
  if (fs.existsSync(manifestPath)) {
    const content = fs.readFileSync(manifestPath, 'utf-8');
    // Keep sample items that start with sample-
    const match = content.match(/window\.DJ_GALLERY_ITEMS\s*=\s*(\[[\s\S]*?\]);/);
    if (match) {
      // Extract samples
      const parsed = eval(match[1]);
      sampleItems = parsed.filter((item) => String(item.id).startsWith('sample-'));
    }
  }
} catch (err) {
  console.warn('Could not read existing samples, using defaults.');
}

// Combine: Local uploads first, then sample items
const allItems = [...localItems, ...sampleItems];

const outputContent = `/**
 * DJ John - Event Media Gallery Manifest
 * Automatically generated by scripts/scan-media.js
 * Total items: ${allItems.length} (Local files: ${localItems.length})
 */

window.DJ_GALLERY_ITEMS = ${JSON.stringify(allItems, null, 2)};
`;

fs.writeFileSync(manifestPath, outputContent, 'utf-8');
console.log(`Successfully scanned media folder! Registered ${localItems.length} local files and ${sampleItems.length} samples.`);
